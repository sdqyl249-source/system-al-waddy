// دالة للحصول على الحد الأقصى للمادة حسب الصف
function getMaxQuota(grade, subject) {
    if (SUBJECT_QUOTAS[subject] && SUBJECT_QUOTAS[subject][grade] !== undefined) {
        return SUBJECT_QUOTAS[subject][grade];
    }
    return 0; // في حال عدم وجود المادة أو الصف
}

// دالة للتحقق من إمكانية إضافة حصة جديدة
function canAddLesson(grade, subject, currentCount) {
    const maxAllowed = getMaxQuota(grade, subject);
    if (currentCount >= maxAllowed) {
        alert(`تنبيه: مادة (${subject}) للصف (${grade}) وصلت للحد الأقصى (${maxAllowed} حصص أسبوعياً).`);
        return false;
    }
    return true;
}
