    "اللغة العربية": { "الأول": 7, "الثاني": 7, "الثالث": 7, "الرابع": 6, "الخامس": 4, "السادس": 4 },
    "اللغة الإنكليزية": { "الأول": 2, "الثاني": 2, "الثالث": 2, "الرابع": 2, "الخامس": 3, "السادس": 3 },
    "رياضيات":      { "الأول": 5, "الثاني": 5, "الثالث": 5, "الرابع": 5, "الخامس": 4, "السادس": 4 },
    "علوم":          { "الأول": 2, "الثاني": 2, "الثالث": 2, "الرابع": 2, "الخامس": 2, "السادس": 2 },
